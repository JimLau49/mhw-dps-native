#!/usr/bin/env python3
"""Generate src/game_data_tables.inc from the C# MhwDpsMeter data files.

usage: gen_tables.py <data dir with game-names.json and monster-parts.json> <output .inc>

monster-parts.json keeps HunterPie MonsterData.xml order per monster; normal
(non-severable) parts appear in collision-slot order, so file order is preserved.
"""
import json
import sys
from pathlib import Path


def c_string(text: str) -> str:
    out = []
    for ch in text:
        if ch in '\\"':
            out.append('\\' + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.extend(f'\\x{b:02x}""' for b in ch.encode('utf-8'))
    return '"' + ''.join(out) + '"'


def main() -> int:
    data_dir = Path(sys.argv[1])
    output = Path(sys.argv[2])
    names = json.loads((data_dir / 'game-names.json').read_text(encoding='utf-8'))
    parts = json.loads((data_dir / 'monster-parts.json').read_text(encoding='utf-8'))

    lines = [
        '// Generated by tools/gen_tables.py from the C# MhwDpsMeter data/ folder. Do not edit.',
        '// Stage/weapon/monster ids follow SharpPluginLoader enums; part tables are derived',
        '// from HunterPie MonsterData.xml (Apache-2.0).',
        '',
    ]
    # Weapons are not generated: game-names.json follows SPL 0.0.7.2, whose enum swapped
    # the bowguns (game id 12 is Heavy Bowgun). src/game_data.cpp hardcodes them.
    for group, symbol in (('stages', 'kStageNames'), ('monsters', 'kMonsterNames')):
        lines.append(f'static const NameEntry {symbol}[] = {{')
        for key, entry in sorted(names[group].items(), key=lambda kv: int(kv[0])):
            lines.append(f'    {{{int(key)}, {c_string(entry["key"])}, {c_string(entry["name"])}}},')
        lines.append('};')
        lines.append('')

    lines.append('static const PartEntry kMonsterParts[] = {')
    for monster, table in parts['monsters'].items():
        for part_id, entry in table.items():
            severable = 'true' if entry.get('severable') else 'false'
            lines.append(f'    {{{int(monster)}, {int(part_id)}, {severable}, {c_string(entry["name"])}}},')
    lines.append('};')
    lines.append('')
    output.write_text('\n'.join(lines), encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
